export function t(locale: Locale, key: UiKey) {
  return uiDictionary[locale]?.[key] || uiDictionary[defaultLocale][key];
}

export function getManualTranslation(text: string, locale: Locale) {
  if (locale === defaultLocale) return text;

  const dictionary = commonPhraseTranslations[locale as Exclude<Locale, "en">];
  const uiMatch = Object.entries(englishUi).find(([, value]) => value === text);

  if (uiMatch) {
    return t(locale, uiMatch[0] as UiKey);
  }

  return dictionary[text];
}
