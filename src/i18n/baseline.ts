function buildLocaleTable(localeIndex: 1 | 2 | 3): Record<string, string> {
  return Object.fromEntries(
    BASELINE_ROWS.map((row) => [row[0], row[localeIndex]]),
  );
}

export const BASELINE_TRANSLATIONS: Record<TargetLocale, Record<string, string>> = {
  "fr-CA": buildLocaleTable(1),
  "zh-Hant": buildLocaleTable(2),
  "ja-JP": buildLocaleTable(3),
};

/** Source strings are exported with the Studio UI catalog for future maintenance. */
export const BASELINE_UI_SOURCE_STRINGS = BASELINE_ROWS.map(([source]) => source);

export function baselineText(locale: SupportedLocale, source: string): string {
  if (locale === "en-CA") return source;
  return BASELINE_TRANSLATIONS[locale][source] ?? source;
}

export function hasBaselineTranslation(locale: TargetLocale, source: string): boolean {
  return Object.prototype.hasOwnProperty.call(BASELINE_TRANSLATIONS[locale], source);
}
